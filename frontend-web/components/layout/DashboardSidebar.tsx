function DashboardSidebarContent({ items: allItems, userType }: DashboardSidebarProps) {
  const pathname = usePathname();
  const tNav = useT(navMessages);
  const label = (name: string) => tNav(name as keyof typeof navMessages.en);
  const searchParams = useSearchParams();
  const queryString = searchParams?.toString() || '';
  const currentHref = queryString ? `${pathname}?${queryString}` : pathname;
  const { user } = useAuthStore();
  // Staff only see the pages their role may open (the server enforces it too).
  const items = userType === 'admin' ? allItems.filter((i) => !i.needs || (user?.permissions ?? []).includes(i.needs)) : allItems;

  const [expandedItems, setExpandedItems] = useState<Record<string, boolean>>({});

  const toggleExpand = (name: string, e: React.MouseEvent) => {
    e.preventDefault();
    e.stopPropagation();
    setExpandedItems((prev) => ({
      ...prev,
      [name]: !(prev[name] ?? true),
    }));
  };

  const allHrefs = items.flatMap((item) => [
    item.href,
    ...(item.subItems?.map((s) => s.href) || []),
  ]);

  const isItemActive = (href: string): boolean => {
    const [itemPath, itemQuery] = href.split('?');
    if (itemQuery) {
      // Sub-view items (e.g. ?view=inventory): require exact href match
      return currentHref === href;
    }
    if (itemPath === '/dashboard') {
      return pathname === itemPath;
    }
    // If current URL has a query string and another item/sub-item matches it exactly, a bare href is not active
    if (queryString && currentHref !== href && allHrefs.some((h) => h === currentHref)) {
      return false;
    }
    const matches = pathname === itemPath || (pathname?.startsWith(`${itemPath}/`) ?? false);
    if (!matches) return false;

    // If another item in items/subItems is a more specific match for pathname or currentHref, that one wins
    const moreSpecificActive = allHrefs.some((other) => {
      if (other === href) return false;
      const [otherPath, otherQuery] = other.split('?');
      if (otherQuery) {
        return other.startsWith(`${itemPath}?`) && currentHref === other;
      }
      if (otherPath.startsWith(`${itemPath}/`)) {
        return pathname === otherPath || (pathname?.startsWith(`${otherPath}/`) ?? false);
      }
      return false;
    });

    return !moreSpecificActive;
  };

  const effectiveUserType = pathname.startsWith('/riders')
    ? 'rider'
    : pathname.startsWith('/sellers')
    ? 'seller'
    : pathname.startsWith('/admin')
    ? 'admin'
    : pathname === '/hub' || pathname.startsWith('/hub/')
    ? 'hub_manager'
    : userType;

  const getUserTypeLabel = () => {
    switch (effectiveUserType) {
      case 'admin': return 'Administrator';
      case 'seller': return 'Seller';
      case 'rider': return 'Rider Fleet';
      case 'hub_manager': return 'Hub manager';
      default: return 'Customer';
    }
  };

  // Flame for customer/admin, dark slate for seller, emerald for rider
  const accentColor = effectiveUserType === 'seller' ? '#0F172A' : effectiveUserType === 'rider' ? '#059669' : '#FF5500';
  const accentSoft = effectiveUserType === 'seller' ? '#F1F5F9' : effectiveUserType === 'rider' ? '#ECFDF5' : '#FFF5ED';
  const accentText = effectiveUserType === 'seller' ? '#0F172A' : effectiveUserType === 'rider' ? '#065F46' : '#FF5500';

  const getIcon = (iconKey: string) => {
    const IconComponent = IconComponents[iconKey] || DefaultIcon;
    return IconComponent;
  };

  return (
    <aside
      className="w-64 h-full overflow-y-auto bg-white border-e border-slate-200"
    >
      <div className="px-4 py-6">

        {/* Menu Label */}
        <div className="px-3 mb-2">
          <span className="eyebrow">{tNav('menu')}</span>
        </div>

        {/* Navigation Items */}
        <nav className="space-y-1">
          {items.map((item) => {
            const hasSubItems = Boolean(item.subItems && item.subItems.length > 0);
            const isChildActive = Boolean(item.subItems?.some((sub) => isItemActive(sub.href)));
            const isSelfActive = isItemActive(item.href) && !isChildActive;
            const isSectionActive = isSelfActive || isChildActive;
            const isExpanded = expandedItems[item.name] !== undefined ? expandedItems[item.name] : isSectionActive;
            const IconComponent = item.icon ? getIcon(item.icon) : null;

            return (
              <div key={item.name} className="space-y-1">
                <div className="flex items-center">
                  <Link
                    href={item.href}
                    className="group flex-1 flex items-center gap-3 px-3 py-2.5 rounded-xl transition-all duration-200 relative"
                    style={{
                      background: isSelfActive ? accentSoft : 'transparent',
                      color: isSectionActive ? accentText : 'var(--ink-600)',
                      fontWeight: isSectionActive ? 600 : 400,
                    }}
                  >
                    {IconComponent && (
                      <IconComponent
                        className="w-5 h-5 flex-shrink-0"
                      />
                    )}
                    <span className="flex-1 text-[14px]">{label(item.name)}</span>
                    {item.badge !== undefined && item.badge > 0 && (
                      <span
                        className="text-xs font-medium px-2 py-0.5 rounded-full min-w-[20px] text-center"
                        style={{ background: accentColor, color: 'var(--cream-50)' }}
                      >
                        {item.badge > 99 ? '99+' : item.badge}
                      </span>
                    )}
                  </Link>

                  {hasSubItems && (
                    <button
                      type="button"
                      onClick={(e) => toggleExpand(item.name, e)}
                      aria-label={tNav(isExpanded ? 'collapse' : 'expand', { name: label(item.name) })}
                      className="p-2 me-1 text-slate-400 hover:text-slate-700 hover:bg-slate-100 rounded-lg transition-colors cursor-pointer"
                    >
                      <svg
                        className={`w-3.5 h-3.5 transition-transform duration-200 ${isExpanded ? 'rotate-180' : ''}`}
                        fill="none"
                        viewBox="0 0 24 24"
                        stroke="currentColor"
                        strokeWidth={2.5}
                      >
                        <path strokeLinecap="round" strokeLinejoin="round" d="M19.5 8.25l-7.5 7.5-7.5-7.5" />
                      </svg>
                    </button>
                  )}
                </div>

                {hasSubItems && isExpanded && (
                  <div className="ms-5 ps-3.5 py-1 space-y-1 border-s-2 border-slate-200">
                    {item.subItems!.map((sub) => {
                      const isSubActive = isItemActive(sub.href);
                      return (
                        <Link
                          key={sub.href}
                          href={sub.href}
                          className="flex items-center gap-2.5 px-3 py-2 rounded-xl text-xs font-semibold transition-all duration-150 relative group/sub"
                          style={{
                            background: isSubActive ? accentSoft : 'transparent',
                            color: isSubActive ? accentText : '#64748B',
                            fontWeight: isSubActive ? 700 : 500,
                          }}
                        >
                          {sub.icon ? (
                            (() => {
                              const SubIconComponent = getIcon(sub.icon);
                              return <SubIconComponent className="w-4 h-4 shrink-0" />;
                            })()
                          ) : (
                            <span
                              className={`w-1.5 h-1.5 rounded-full transition-all shrink-0 ${
                                isSubActive ? 'bg-slate-900 scale-125' : 'bg-slate-300 group-hover/sub:bg-slate-400'
                              }`}
                            />
                          )}
                          <span className="flex-1 truncate">{label(sub.name)}</span>
                          {sub.badge !== undefined && sub.badge > 0 && (
                            <span
                              className="text-[11px] font-bold px-1.5 py-0.5 rounded-full"
                              style={{ background: accentColor, color: '#FFFFFF' }}
                            >
                              {sub.badge}
                            </span>
                          )}
                        </Link>
                      );
                    })}
                  </div>
                )}
              </div>
            );
          })}
        </nav>

        {/* Quick Actions Card - Role Aware */}
        {effectiveUserType === 'rider' ? (
          <div className="mt-8 p-4 rounded-2xl bg-gradient-to-br from-emerald-50 to-teal-100/60 border border-emerald-200/80 shadow-xs">
            <h4 className="font-bold text-xs mb-1 text-slate-900 flex items-center gap-1.5">
              <svg className="w-4 h-4 text-emerald-600" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M9 12.75L11.25 15 15 9.75m-3-7.036A11.959 11.959 0 013.598 6 11.99 11.99 0 003 9.749c0 5.592 3.824 10.29 9 11.623 5.176-1.332 9-6.03 9-11.622 0-1.31-.21-2.571-.598-3.751h-.152c-3.196 0-6.1-1.248-8.25-3.285z" />
              </svg>
              {tNav('riderHelpTitle')}
            </h4>
            <p className="text-[11px] mb-3 text-slate-600 font-medium">
              {tNav('riderHelpText')}
            </p>
            <Link
              href="/support"
              className="flex items-center justify-center gap-1.5 w-full py-2 text-xs font-bold rounded-xl transition-all active:scale-95 shadow-sm bg-emerald-600 hover:bg-emerald-700 text-white"
            >
              <svg className="w-3.5 h-3.5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M8.625 12a.375.375 0 11-.75 0 .375.375 0 01.75 0zm0 0H8.25m4.125 0a.375.375 0 11-.75 0 .375.375 0 01.75 0zm0 0H12m4.125 0a.375.375 0 11-.75 0 .375.375 0 01.75 0zm0 0h-.375M21 12c0 4.556-4.03 8.25-9 8.25a9.764 9.764 0 01-2.555-.337A5.972 5.972 0 015.41 20.97a5.969 5.969 0 01-.474-.065 4.48 4.48 0 00.978-2.025c.09-.457-.133-.901-.467-1.226C3.93 16.178 3 14.189 3 12c0-4.556 4.03-8.25 9-8.25s9 3.694 9 8.25z" />
              </svg>
              {tNav('contactSupport')}
            </Link>
          </div>
        ) : null}
      </div>
    </aside>
  );
}

