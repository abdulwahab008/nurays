import { createElement, Fragment, type ReactNode } from 'react';
import { defineMessages } from '..';

/**
 * Fills a translated sentence whose placeholders are elements (a bold amount, a link):
 * richText('Add {amount} more', { amount: <strong>…</strong> }). Word order stays the translator's.
 */
export function richText(template: string, nodes: Record<string, ReactNode>): ReactNode[] {
  return template
    .split(/(\{\w+\})/g)
    .filter((part) => part !== '')
    .map((part, i) => {
      const name = /^\{(\w+)\}$/.exec(part)?.[1];
      return createElement(Fragment, { key: i }, name && name in nodes ? nodes[name] : part);
    });
}

