type KitchenT = (key: keyof typeof kitchenOrderMessages.en & string, vars?: Record<string, string | number>) => string;
type CommonT = (key: keyof typeof commonMessages.en & string) => string;

const KITCHEN_STATUS_KEYS: Record<string, keyof typeof kitchenOrderMessages.en> = {
  pending: 'statusNew',
  confirmed: 'badge.confirmed',
  preparing: 'badge.preparing',
  ready: 'badge.ready',
  dispatched: 'badge.outForDelivery',
  in_transit: 'badge.outForDelivery',
  delivered: 'badge.completed',
  completed: 'badge.completed',
  cancelled: 'badge.cancelled',
};

/** An order status in the kitchen's words, the same on the dashboard, the orders list and the order page. */
export function kitchenStatusLabel(status: string, t: KitchenT, tc: CommonT): string {
  const own = KITCHEN_STATUS_KEYS[status];
  if (own) return t(own);
  const key = statusKey(status);
  return key in commonMessages.en ? tc(key) : status;
}

/** A payment method's words, or the raw value for one we don't know. */
export function paymentMethodLabel(method: string | undefined, tc: CommonT): string {
  if (!method) return '';
  const key = `pay.${method}` as keyof typeof commonMessages.en;
  return key in commonMessages.en ? tc(key) : method.replace(/_/g, ' ');
}

/** A payment status's words, or the raw value for one we don't know. */
export function paymentStatusLabel(status: string | undefined, t: KitchenT): string {
  if (!status) return '';
  const key = `payStatus.${status}` as keyof typeof kitchenOrderMessages.en;
  return key in kitchenOrderMessages.en ? t(key) : status.replace(/_/g, ' ');
}
